def _flat(word: str) -> str:
    """One lookup spelling: lowercase alphanumerics only (`thank_you`, `thank-you`, `thank you` -> `thankyou`)."""
    return re.sub(r"[^a-z0-9]+", "", str(word or "").lower())


_TOKEN_CLASS = {t: "core" for t in ACTION_BANK}
_TOKEN_CLASS.update({t: "ext" for t in EXTENDED_BANK})

_BANK_OF = {**ACTION_BANK, **EXTENDED_BANK}   # token -> {"emoji", "aliases"} (no key sits in both)

BANK_VERSION = "core-36-unicode-15.1-v2"
_CORE_LOOKUP: dict[str, str] = {}
_EXACT: dict[str, list[str]] = {}
_ALIASES: dict[str, list[str]] = {}
for _tok, _row in ACTION_BANK.items():
    for _word in [_tok, *_row["aliases"]]:
        _CORE_LOOKUP.setdefault(_flat(_word), _tok)
for _tok, _row in EXTENDED_BANK.items():
    _EXACT.setdefault(_flat(_tok), []).append(_tok)
    for _word in _row["aliases"]:
        _bucket = _ALIASES.setdefault(_flat(_word), [])
        if _tok not in _bucket:
            _bucket.append(_tok)


def is_ios_emoji(text: str | None) -> bool:
    """Whether the complete first cluster is a supported Unicode 15.1 sequence."""
    from .emoji import first_emoji, valid
    return valid(first_emoji(text))


def _candidates(key: str | None, tags: list | tuple | None) -> list[str]:
    blobs = [key, *list(tags or [])]
    # Whole fields all get a chance before split-word fallback.
    words = [_flat(blob) for blob in blobs]
    words += [_flat(w) for blob in blobs for w in re.split(r"[^a-z0-9]+", str(blob or "").lower())]
    return list(dict.fromkeys(w for w in words if w and not w.isdigit()))


def _lookup(word: str, emoji: str | None = None) -> list[str]:
    from .emoji import base, first_emoji, valid
    if word in _CORE_LOOKUP:
        return [_CORE_LOOKUP[word]]
    choices = list(_EXACT.get(word) or _ALIASES.get(word) or [])
    glyph = first_emoji(emoji)
    if len(choices) > 1 and valid(glyph):
        narrowed = [t for t in choices if base(_BANK_OF[t]["emoji"]) == base(glyph)]
        if narrowed:
            choices = narrowed
    return choices


def resolve(key: str | None, tags: list | tuple | None = None, *, emoji: str | None = None,
            action: str | None = None, limit: int = 4) -> dict:
    """Stable JSON result: hits, candidates and reason. Ambiguity never picks a row."""
    cap = max(1, min(4, int(limit)))
    first, ambiguous = None, []
    if action:
        if action not in _BANK_OF:
            raise ValueError("Choose a canonical action from the emoji bank")
        first = action
    else:
        for word in _candidates(key, tags):
            choices = _lookup(word, emoji)
            if len(choices) > 1:
                return {"hits": [], "candidates": choices, "reason": "ambiguous_alias"}
            if choices:
                first = choices[0]
                break
    if not first:
        return {"hits": [], "candidates": [], "reason": "unmapped"}
    tokens = [first]
    for blob in [key, *list(tags or [])]:
        if len(tokens) >= cap:
            break
        choices = _lookup(_flat(blob), emoji)
        if len(choices) > 1:
            # A recorded human primary also resolves its ambiguous source alias.
            if action and action in choices:
                continue
            ambiguous.extend(t for t in choices if t not in ambiguous)
        elif choices and choices[0] not in tokens:
            tokens.append(choices[0])
    return {"hits": [(t, list(_BANK_OF[t]["aliases"])) for t in tokens],
            "candidates": ambiguous, "reason": "ambiguous_alias" if ambiguous else None}


def canonical_for(key: str | None, tags: list | tuple | None = None) -> tuple[str, list[str]] | None:
    hits = resolve(key, tags, limit=1)["hits"]
    return hits[0] if hits else None


def canonical_all(key: str | None, tags: list | tuple | None = None, limit: int = 4) -> list[tuple[str, list[str]]]:
    return resolve(key, tags, limit=limit)["hits"]


def canonical_mood(key: str | None, tags: list | tuple | None = None) -> tuple[str, list[str]] | None:
    """Legacy mood association, independently of object matching; queues use tokens_from_stickers."""
    for word in _candidates(key, tags):
        tok = _CORE_LOOKUP.get(word)
        if tok:
            return tok, list(ACTION_BANK[tok]["aliases"])
    return None


def fallback_tag(key: str | None = None, tags: list | tuple | None = None, exclude: list | tuple | None = None) -> str:
    """A deterministic tag segment when nothing maps: the tags joined (they are the curated search words),
    else the key's words, else `sticker`. Subject/pack words (`exclude`) are stripped and repeats collapsed, so
    `generic_emojis_grumpy` + `[grumpy, arms, crossed]` becomes `grumpy_arms_crossed`, never
    `generic_emojis_grumpy_grumpy_arms_crossed`. Each word is lowercase alphanumerics, joined with `_`."""
    words = []
    for t in (list(tags) if tags else [key]):
        words.extend(w for w in re.split(r"[^a-z0-9]+", str(t or "").lower()) if w)
    banned: set[str] = set()
    for t in (list(exclude) if exclude else []):
        banned.update(w for w in re.split(r"[^a-z0-9]+", str(t or "").lower()) if w)
    seen, out, plain, pseen = set(), [], [], set()
    for w in words:
        if w not in pseen:
            pseen.add(w)
            plain.append(w)
        if w not in banned and w not in seen:
            seen.add(w)
            out.append(w)
    return "_".join(out or plain) or "sticker"


